/*一维数组定义：
1.定义一个长度为10的整型数组a且自动初始化为0：int a[10]{};
2.定义同时初始化：int b[5]={1,2,3,4,5};
3.只给一部分赋值，剩下自动补0；int c[6]={1,2};
4.不写长度，自动根据初始化数量确定大小：int d[]={1,2,3,4,5};															*/
#include<iostream>
using namespace std;
int main()
{
	int a[10]{};
	for (int i = 0; i < 10; i++)				//把一个一维数组里的数逐个与另一个数比大小，统计有多少个数比另一个数小
	{														//另外再新建一个一维数组，把比另一个数小的数存入新的一维数组里，
		cin >> a[i];
	}
	int b = 0;
	cin >> b;
	int c[10]{};
	int d = 0;
	for (int i = 0; i < 10; i++)
	{
		if (a[i] <= b + 30)
		{
			c[i] = a[i];
			d++;
		}
	}
	cout << d;
	return 0;
}